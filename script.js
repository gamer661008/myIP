// 切換語言
function switchLanguage(lang) {
    const data = i18n[lang];
    if (!data) return;

    document.body.style.fontFamily = data.font;
    
    document.getElementById('mainTitle').innerText = data.mainTitle;
    document.getElementById('descText').innerText = data.descText;
    document.getElementById('searchBtn').innerText = data.searchBtn;
    document.getElementById('labelIp').innerText = data.labelIp;
    document.getElementById('labelIsp').innerText = data.labelIsp;
    document.getElementById('labelAsn').innerText = data.labelAsn;
    document.getElementById('labelType').innerText = data.labelType;
    document.getElementById('labelLocation').innerText = data.labelLocation;

    document.getElementById('cookieTitle').innerText = data.cookieTitle;
    document.getElementById('cookieText').innerText = data.cookieText;
    document.getElementById('cookieAcceptBtn').innerText = data.cookieAccept;
    document.getElementById('cookieDeclineBtn').innerText = data.cookieDecline;

    const adStatus = document.getElementById('adStatusText');
    if (adStatus) {
        if (localStorage.getItem('royal_cookie_consent') === 'true') {
            adStatus.innerText = data.adLoading;
        } else {
            adStatus.innerText = data.adWait;
        }
    }
}

// 串接 FreeIPAPI.com 查詢邏輯
async function performIpLookup() {
    const currentLang = document.getElementById('langSelector').value;
    const langData = i18n[currentLang];
    const inputIp = document.getElementById('ipInput').value.trim();
    
    const valIp = document.getElementById('valIp');
    const valIsp = document.getElementById('valIsp');
    const valAsn = document.getElementById('valAsn');
    const valType = document.getElementById('valType');
    const valLocation = document.getElementById('valLocation');

    valIp.innerText = inputIp || langData.detecting;
    valIsp.innerText = langData.loading;
    valAsn.innerText = langData.loading;
    valType.innerText = langData.loading;
    valLocation.innerText = langData.loading;

    try {
        const response = await fetch(`https://freeipapi.com{inputIp}`);
        if (!response.ok) throw new Error('API連線回應異常');
        const data = await response.json();

        let connectionTypeDisplay = data.connectionType || '--';
        if (connectionTypeDisplay.toLowerCase() === 'cellular') {
            connectionTypeDisplay = langData.typeMobile;
        } else if (connectionTypeDisplay.toLowerCase() === 'fixed') {
            connectionTypeDisplay = langData.typeBroadband;
        }

        valIp.innerText = data.ipAddress || 'Unknown';
        valIsp.innerText = data.isp || 'Unknown Provider';
        valAsn.innerText = data.asn ? `AS${data.asn}` : '--';
        valType.innerText = connectionTypeDisplay;
        
        const city = data.cityName || '';
        const country = data.countryName || '';
        valLocation.innerText = city ? `${city}, ${country}` : country;

    } catch (error) {
        console.error('FreeIPAPI Request Error:', error);
        valIp.innerText = '❌';
        valIsp.innerText = '❌';
        valAsn.innerText = '❌';
        valType.innerText = '❌';
        valLocation.innerText = langData.error;
    }
}

/**
 * ⚡ 廣告動態載入
 */
function loadAdScripts() {
    const currentLang = document.getElementById('langSelector').value;
    const adStatus = document.getElementById('adStatusText');
    if (adStatus) adStatus.innerText = i18n[currentLang].adLoading;

    // 1. Google AdSense 
    const adsenseScript = document.createElement('script');
    adsenseScript.async = true;
    adsenseScript.src = 'https://googlesyndication.com';
    adsenseScript.crossOrigin = 'anonymous';
    document.head.appendChild(adsenseScript);

    // 2. 第三方廣告
    const partnerScript = document.createElement('script');
    partnerScript.async = true;
    partnerScript.src = 'https://araplhn.org';
    document.head.appendChild(partnerScript);
}

/**
 * 📜 處理隱私與 LocalStorage 同意機制
 */
function handleConsentResponse(isAccepted) {
    localStorage.setItem('royal_cookie_consent', isAccepted);
    const banner = document.getElementById('cookieBanner');
    if (banner) banner.classList.add('hidden');
    if (isAccepted) {
        loadAdScripts();
    }
}

function checkCookieConsent() {
    const consent = localStorage.getItem('royal_cookie_consent');
    const banner = document.getElementById('cookieBanner');

    if (consent === 'true') {
        loadAdScripts();
    } else if (consent === 'false') {
        const adStatus = document.getElementById('adStatusText');
        if (adStatus) adStatus.style.display = 'block';
    } else {
        if (banner) banner.classList.remove('hidden');
    }
}

// 🏛️ 監聽 DOM 確保百分百安全綁定按鈕點擊事件
window.addEventListener('DOMContentLoaded', () => {
    const langSelector = document.getElementById('langSelector');
    if (langSelector) {
        langSelector.addEventListener('change', (e) => {
            switchLanguage(e.target.value);
        });
    }

    const searchBtn = document.getElementById('searchBtn');
    if (searchBtn) {
        searchBtn.addEventListener('click', () => {
            performIpLookup();
        });
    }

    const cookieAcceptBtn = document.getElementById('cookieAcceptBtn');
    if (cookieAcceptBtn) {
        cookieAcceptBtn.addEventListener('click', () => {
            handleConsentResponse(true);
        });
    }

    const cookieDeclineBtn = document.getElementById('cookieDeclineBtn');
    if (cookieDeclineBtn) {
        cookieDeclineBtn.addEventListener('click', () => {
        handleConsentResponse(false);
        });
        }
        checkCookieConsent();
    });
